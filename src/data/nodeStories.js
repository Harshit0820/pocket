export function nodeStory(node, company) {
  const raw = BY_ID[node.id] || BY_KIND[node.kind] || node.blurb
  return raw
    .replaceAll('{name}', company.name)
    .replaceAll('{asset}', company.asset)
    .replaceAll('{verb}', company.verb)
}
